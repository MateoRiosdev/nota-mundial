const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || undefined, headless: true, args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ extraHTTPHeaders: { 'x-vercel-ip-country': 'PE' }, viewport: { width: 1280, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    let calls = 0;
    page.on('request', r => { if (r.url().includes('/api/news?')) calls++; });
    const base = process.env.PLANNER_TEST_URL || 'http://127.0.0.1:3000';
    await page.goto(base + '/es');
    const selector = page.getByRole('heading', { name: 'Selecciona tu país', exact: true });
    await selector.waitFor();
    const summary = selector.locator('..').locator('div').filter({ has: page.locator('strong', { hasText: '0-20' }) }).first();
    await summary.waitFor();
    assert.match(await summary.innerText(), /Perú/);
    assert((await summary.boundingBox()).y < (await selector.boundingBox()).y);
    assert.equal(await page.locator('link[rel="icon"]').getAttribute('href'), '/favicon.svg');
    const panel = page.locator('details').filter({ has: page.locator('summary', { hasText: 'Explora tu futuro' }) });
    assert.equal(await panel.getAttribute('open'), null);
    assert.equal(calls, 0);
    await panel.locator('summary').click();
    await panel.getByRole('heading', { name: 'PRONABEC', exact: true }).waitFor();
    assert.equal(calls, 0);
    await panel.getByRole('button', { name: 'Empleo y prácticas', exact: true }).click();
    assert.equal(await panel.getByRole('heading', { name: 'PRONABEC' }).count(), 0);
    await panel.getByRole('heading', { name: 'Empleos Perú', exact: true }).waitFor();
    await page.getByPlaceholder('Buscar país...').fill('España');
    await page.getByRole('button', { name: 'España 0-10', exact: true }).click();
    await panel.getByRole('button', { name: 'Todo', exact: true }).click();
    await panel.getByRole('heading', { name: 'Becas de Educación', exact: true }).waitFor();
    assert.equal(await panel.getByRole('heading', { name: 'PRONABEC' }).count(), 0);
    await panel.getByRole('searchbox').fill('does-not-exist');
    await panel.getByText('No hay portales que coincidan', { exact: false }).waitFor();
    await panel.getByRole('searchbox').fill('');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    const artifacts = process.env.PLANNER_ARTIFACTS || '/tmp/nota-mundial-browser-tests';
    await fs.mkdir(artifacts, { recursive: true });
    await panel.screenshot({ path: path.join(artifacts, 'opportunities-mobile.png') });
    await page.setViewportSize({ width: 1280, height: 1000 });
    await page.getByPlaceholder('Buscar país...').fill('Perú');
    await page.getByRole('button', { name: 'Perú 0-20', exact: true }).click();
    await panel.getByRole('heading', { name: 'PRONABEC', exact: true }).waitFor();
    await panel.screenshot({ path: path.join(artifacts, 'opportunities-desktop.png') });
    assert.equal(calls, 0, 'The directory must never request the news API');
    assert.equal(await panel.getByRole('button', { name: 'Noticias', exact: true }).count(), 0);
    assert.deepEqual(errors, []);
    await context.close();
    console.log('PASS: automatic Peru summary, circular favicon reference, official resources without news API requests, filters, country switch, dark mobile layout; no browser errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
